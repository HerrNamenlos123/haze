// The point of this port is to compute exactly what the library computes,
// down to the last bit, so a stroke looks the same here as in the web app and
// the outlines the web app stored in a file are the ones this recomputes. So
// it follows the JavaScript operation for operation, in the same order:
//
//   - lengths use Math.hypot's algorithm (scale by the larger, compensated
//     sum, sqrt), not sqrt(x*x + y*y), which rounds differently;
//   - the caps rotate by the angles the library's own loops produce, which
//     step by accumulating 1/13 or 1/29 and so are not i/13 -- the end cap
//     has 29 points, not 28 -- with the sines and cosines V8 computes for
//     them, tabulated below, since libm may round the odd one differently;
//   - no multiply-add is fused (see the pragma).
//
// Taper, flat caps and custom easings are not ported: nothing here passes
// them, and without them the library behaves as with its defaults.

#include <math.h>
#include <stdlib.h>
#include <string.h>

#include "public/perfect_freehand.h"

// A fused multiply-add rounds once where JavaScript rounds twice.
#if defined(__clang__)
#pragma clang fp contract(off)
#elif defined(__GNUC__)
#pragma GCC optimize("fp-contract=off")
#endif

typedef struct {
  double x;
  double y;
} hz_pf_vec_t;

typedef struct {
  hz_pf_vec_t point;
  double pressure;
  hz_pf_vec_t vector;
  double distance;
  double runningLength;
} hz_pf_stroke_point_t;

typedef struct {
  hz_pf_vec_t point;
  // The JavaScript point's third element: absent (undefined) for the points
  // the library interpolates itself.
  double pressure;
  int hasPressure;
} hz_pf_input_t;

typedef struct {
  hz_pf_vec_t* items;
  size_t count;
  size_t capacity;
} hz_pf_vec_list_t;

typedef struct hz_pf_context_t hz_pf_context_t;

// Everything pf_compute works in belongs to the context and is kept from one
// run to the next, so a context that computes stroke after stroke allocates
// only until it has seen the longest of them. A document has thousands of
// strokes: with the working arrays malloc'd and freed per run, they were some
// twenty allocations each.
struct hz_pf_context_t {
  hz_pf_input_t* points;
  size_t count;
  size_t capacity;

  double size;
  double thinning;
  double smoothing;
  double streamline;
  int simulatePressure;
  int last;

  hz_pf_stroke_point_t* strokePoints;
  size_t strokePointCapacity;
  hz_pf_vec_list_t leftPts;
  hz_pf_vec_list_t rightPts;

  hz_pf_vec_t* outline;
  size_t outlineCount;
  size_t outlineCapacity;

  // Of the outline, found on first request (see hz_pf_bounds).
  int hasBounds;
  hz_pf_vec_t boundsMin;
  hz_pf_vec_t boundsMax;
};

